function HM_affine(u)
    #check that matrix u of type ZZMatrix is well-defined
    if !(u isa ZZMatrix)
        println("\nError: matrix must be of type ZZMatrix")
        return nothing
    end
    if ncols(u)!=nrows(u) 
        println("\nError: matrix must be square")
        return nothing
    end
    n=ncols(u)    
    for j in 1:n
        if u[j,j]!= 0
            println("\nError: diagonal entries must be 0")
            return nothing
        end
    end
    
    # define the ring in dependence of n
    vars=Symbol.("x" .* string.(1:n))
    R, x=polynomial_ring(QQ,vars)
    o=zero(R)
    
    R2=free_module(R,2)
    
    # define the generating vectors for the modules M_i
    vectors1=Vector(undef,n)
    vectors2=Vector(undef,n)
    vectors3=Vector(undef,n)
    up=Array{Int}(undef,n,n)
    um=Array{Int}(undef,n,n)
    for i in 1:n
        vectors1[i] = R2([x[i],o])
        vectors2[i] = R2([o,x[i]])
        for j in 1:n
            if u[j,i]>0
                up[i,j]=u[j,i]
                um[i,j]=0
                elseif u[j,i]<0
                    up[i,j]=0
                    um[i,j]=-u[j,i]
                else
                    up[i,j]=0
                    um[i,j]=0
            end
        end
        p1=x[1]^0
        p2=x[1]^0
        for j in 1:n
            p1=p1*x[j]^up[i,j]
            p2=p2*x[j]^um[i,j]
        end
        vectors3[i] = R2([p1,-p2])
    end

    #Define the modules M_i as submodules R^2 generated by vectors1, 2, 3[i]
    inc=Vector(undef,n)
    M=Vector(undef,n)
    for i in 1:n
        M[i], inc[i]=sub(R2,[vectors1[i],vectors2[i],vectors3[i]])
    end

    #Define the modules for intersection
    inc_int=Vector(undef,n)
    M_int=Vector(undef,n)
    M_int[1]=M[1]
    inc_int[1]=inc[1]
    for i in 2:n
        M_int[i], inc_int[i]=intersect(M[i],M_int[i-1])
    end

    #Define the intersection \bigcap_{i=1}^nM_i as a submodule of R2
    inc_fin=compose(inc_int[n],inc[n])
    M_is, inc_is=image(inc_fin) 
    
    #compute a presentation in order to get possibly less generators
    pres=presentation(M_is,minimal=true)
    N, incN=image(map(pres,0))
    l=length(gens(N))
    genvec=Vector{SubquoModuleElem{QQMPolyRingElem}}(undef,l)
    for i in 1:l
        genvec[i]=N[i]
    end
    M_is, incM_is =sub(R2, genvec)
   
    return R, R2, M_is, incM_is
end


